"""Private Workflow dependency seams; public callers use CampaignRequest."""

from __future__ import annotations
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Protocol, Callable, TYPE_CHECKING, Optional
from aka.contracts.agent import Agent
from aka.contracts.problem_provider import ProblemProvider
from aka.contracts.workspace import SourceProvider, CandidateWorkspace
from aka.contracts.problem import LoadedProblem
from aka.contracts.workflow import CampaignRequest
import subprocess

if TYPE_CHECKING:
    from .models import VerificationResult
    from .campaign import Campaign
    from aka.legacy.application.workflow_services import WorkflowServices


class BaselineOperations(Protocol):
    def evaluator_directive(self) -> str: ...
    def install_native_evaluator(self) -> None: ...
    def install_profile_driver(self) -> None: ...
    def native_v0_readme(self, *, generalized: bool) -> str: ...
    def print_v0_evaluator_output(
        self, test: subprocess.CompletedProcess[str]
    ) -> None: ...
    def run_v0_evaluator(self) -> dict: ...
    def write_v0_baseline_report(self, result: dict, source_commit: str) -> Path: ...
    def finalize_v0_measurement(
        self, result: dict, source_commit: str, *, extra_paths: tuple[str, ...] = ()
    ) -> None: ...
    def setup_baseline_native(self, op_dir: Path, *, generalized: bool) -> None: ...
    def setup_baseline_sol(self, op_dir: Path) -> None: ...
    def framework_baseline_smoke_shape_ids(self, *, limit: int = 3) -> list[str]: ...
    def ensure_framework_baseline_solution_manifest(self) -> None: ...
    def framework_baseline_smoke_command(self, n: int) -> tuple[str, str]: ...
    def restore_immutable_baseline_paths(self, baseline_commit: str) -> list[str]: ...
    def framework_baseline_problem(
        self, v0_blob: str, baseline_commit: str, *, include_policy_review: bool = True
    ) -> str: ...
    def framework_baseline_external_gates(
        self, n: int
    ) -> tuple[Optional[dict], str]: ...
    def supplemental_numerical_feedback(
        self,
        workspace: Path | None = None,
        *,
        standard_correctness_passed: bool = False,
    ) -> str: ...
    def validate_framework_baseline(self, n: int) -> tuple[Optional[dict], str]: ...


class EpisodeMeasurements(Protocol):
    def expected_shape_ids(self) -> set[str] | None: ...
    def fast_evaluator_command(self, version: int) -> str: ...
    def fast_verification_result(
        self, episode_workspace: Path, *, memory_version: int
    ) -> VerificationResult: ...
    def iso_timestamp(self, value: str) -> float: ...
    def conversion_parity_passes(self, verification: VerificationResult) -> bool: ...
    def representative_candidate_result(
        self, verification: VerificationResult | None
    ) -> dict[str, Any]: ...
    def candidate_shape_latencies(
        self, verification: VerificationResult | None
    ) -> tuple[dict[str, float], int]: ...
    def latest_complete_canonical_performance(
        self,
        workspace: Path,
        *,
        before_version: int,
        expected_shape_ids: set[str] | None,
        required_performance_objective: str | None = None,
    ) -> tuple[dict[str, Any], int] | None: ...
    def latest_complete_episode_performance(
        self,
        episode_workspace: Path | None,
        *,
        expected_shape_ids: set[str] | None,
        required_performance_objective: str | None = None,
    ) -> dict[str, Any] | None: ...
    def episode_evaluation_count(self, episode_workspace: Path) -> int: ...


class CampaignExecution(Protocol):
    def environment(self) -> dict[str, str]: ...
    def directive(self, *, fast: bool = False) -> str: ...
    def framework_baseline_directive(self) -> str: ...
    def run_session(
        self,
        workspace: Path,
        prompt: str,
        timeout: int,
        *,
        agent_cli: str,
        runtime: Any,
        environment: dict[str, str] | None = None,
        remote: bool = False,
        **options: Any,
    ) -> Any: ...


class EpisodeEnvironment(Protocol):
    CONVERT_PERF_TOL: float

    def prepare_campaign(self, campaign: Campaign) -> None: ...
    def link_episode_runtime(self, campaign: Campaign, workspace: Path) -> None: ...
    def episode_directives(
        self, campaign: Campaign, version: int, *, fast: bool = False
    ) -> dict[str, str]: ...
    def candidate_policy_violations(
        self, campaign: Campaign, workspace: Path, *, require_gluon: bool = False
    ) -> list[str]: ...
    def conversion_required(
        self, campaign: Campaign, stall: int, workspace: Path
    ) -> bool: ...
    def candidate_is_gluon(self, workspace: Path) -> bool: ...
    def restored_stall(self, workspace: Path) -> int: ...
    def save_stall(self, workspace: Path, value: int) -> None: ...
    def read_memory(self, workspace: Path, version: int) -> dict | None: ...
    def latest_version(self, workspace: Path) -> int: ...
    def speedup_vs_reference(self, memory: dict) -> float: ...
    def peak_util(self, memory: dict) -> float: ...


class Verifier(Protocol):
    def verify(self, workspace: Path, **options: Any) -> VerificationResult: ...


@dataclass(frozen=True)
class CampaignDependencies:
    agent: Agent
    problem: ProblemProvider
    source: SourceProvider
    candidate: CandidateWorkspace
    evaluation: Callable[[Campaign], BaselineOperations]
    workflow: Callable[[Campaign], str]
    execution: Callable[[Campaign], CampaignExecution]
    prepare_request: Callable[[CampaignRequest, LoadedProblem], CampaignRequest] = (
        lambda request, problem: request
    )
    services: Callable[[Campaign], WorkflowServices] | None = None


# Keep historical private imports usable during downstream migration.
BaselineEvaluation = BaselineOperations
